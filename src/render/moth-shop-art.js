const mothMerchantFrames = new Map();
function mothPixelPolygon(ctx, points, color) {
  ctx.fillStyle = color;
  const top = Math.floor(Math.min(...points.map((p) => p[1]))),
    bottom = Math.ceil(Math.max(...points.map((p) => p[1])));
  for (let y = top; y < bottom; y++) {
    const cross = [],
      line = y + 0.5;
    for (let i = 0; i < points.length; i++) {
      const a = points[i],
        b = points[(i + 1) % points.length];
      if ((a[1] <= line && b[1] > line) || (b[1] <= line && a[1] > line))
        cross.push(a[0] + ((line - a[1]) * (b[0] - a[0])) / (b[1] - a[1]));
    }
    cross.sort((a, b) => a - b);
    for (let i = 0; i + 1 < cross.length; i += 2) {
      const x = Math.ceil(cross[i] - 0.5),
        end = Math.ceil(cross[i + 1] - 0.5);
      ctx.fillRect(x, y, end - x, 1);
    }
  }
}
