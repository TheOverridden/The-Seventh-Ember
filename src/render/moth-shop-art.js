const mothDrawCombatFX = drawCombatFX;
drawCombatFX = function (ctx) {
  mothDrawCombatFX(ctx);
  if (!G.run || !G.player) return;
  for (const f of mothGoods().fields) {
    ctx.save();
    ctx.translate(f.x, f.y);
    ctx.scale(0.32, 0.32);
    ctx.globalAlpha = 0.5 * f.t;
    drawMothMerchant(ctx, 0, 0, save.motion ? 0 : G.tAll);
    ctx.restore();
  }
};
