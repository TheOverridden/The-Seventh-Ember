function drawMothMerchant(ctx, x, y, t = 0) {
  const clock = save.motion ? 0 : Math.max(0, t),
    pose = Math.floor(clock * 1.5) % 8,
    blink = !save.motion && clock % 7.4 > 7.24;
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(mothMerchantFrame(pose, blink), Math.round(x) - 108, Math.round(y) - 115);
  ctx.restore();
}

const mothDrawCombatFX = drawCombatFX;
drawCombatFX = function (ctx) {
  mothDrawCombatFX(ctx);
  if (!G.run || !G.player) return;
  for (const f of mothGoods().fields) {
    ctx.save();
    ctx.translate(f.x, f.y);
    ctx.scale(0.32, 0.32);
    ctx.globalAlpha = 0.5 * f.t;
    drawMothMerchant(ctx, 0, 0, save.motion ? 0 : G.tAll);
    ctx.restore();
  }
};
